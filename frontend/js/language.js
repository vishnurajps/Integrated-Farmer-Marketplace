// ==========================================
// TRANSLATE PAGE
// ==========================================

function changeLanguage(language) {

    const selectedLanguage = translations[language];

    if (!selectedLanguage) {
        return;
    }

    // Translate normal text
    document.querySelectorAll("[data-lang]").forEach(function (element) {

        const key = element.getAttribute("data-lang");

        if (selectedLanguage[key]) {
            element.textContent = selectedLanguage[key];
        }

    });


    // Translate placeholders
    document.querySelectorAll("[data-placeholder]").forEach(function (element) {

        const key = element.getAttribute("data-placeholder");

        if (selectedLanguage[key]) {
            element.placeholder = selectedLanguage[key];
        }

    });


    // Save language globally
    localStorage.setItem("ifmapLanguage", language);

    // Update HTML language
    document.documentElement.lang = language;

    // Update dropdown
    const languageSelector =
        document.getElementById("languageSelector");

    if (languageSelector) {
        languageSelector.value = language;
    }
}


// ==========================================
// LOAD LANGUAGE ON EVERY PAGE
// ==========================================

document.addEventListener("DOMContentLoaded", function () {

    const savedLanguage =
        localStorage.getItem("ifmapLanguage") || "en";

    // Apply saved language automatically
    changeLanguage(savedLanguage);


    // Language dropdown
    const languageSelector =
        document.getElementById("languageSelector");

    if (languageSelector) {

        languageSelector.value = savedLanguage;

        languageSelector.addEventListener("change", function () {

            changeLanguage(this.value);

        });

    }

});